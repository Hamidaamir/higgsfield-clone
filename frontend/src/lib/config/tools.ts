export const TOOLS: Tool[] = [...IMAGE_TOOLS, ...VIDEO_TOOLS, ...AUDIO_TOOLS];

export const toolsByCategory = (category: ToolCategory): Tool[] => TOOLS.filter((t) => t.category === category);

export const getTool = (slug: string): Tool | undefined => TOOLS.find((t) => t.slug === slug);

/** Link target for a tool: the generator when available, otherwise its representative page. */
export const toolHref = (tool: Tool): string => tool.href ?? `/tools/${tool.slug}`;
