export type ToolCategory = "image" | "video" | "audio";

/**
 * `available` tools are backed by a real generator; `preview` tools reproduce the product
 * surface (a representative page) and point at the nearest working workflow.
 */
export type ToolStatus = "available" | "preview";

export interface Tool {
  slug: string;
  name: string;
  description: string;
  category: ToolCategory;
  icon: LucideIcon;
  status: ToolStatus;
  /** Destination for available tools (a generator, optionally with query presets). */
  href?: string;
  badge?: "New" | "Free" | "TOP";
  /** Longer copy for the representative tool page. */
  longDescription: string;
  steps: [string, string, string];
  /** Where a preview tool sends the user to do real work today. */
  fallbackHref: string;
  fallbackLabel: string;
  /** Deterministic photo seed for the tool's cover. */
  seed: string;
}

